# -*- coding: utf-8 -*-
"""Registro curado a mano de la geografia industrial basal argentina.

Fuente unica: ``scripts/industria/Geografia_Industrial_Argentina.md``.

Cada elemento de ``REGISTROS`` es un dict que representa UN nodo productivo
(planta, cantera, puerto, central o polo regional). Las filas agrupadas del
documento fueron desagregadas: "Plantas Pilar, Chacabuco, San Justo, Tres
Arroyos, Pigue" produce cinco registros, "Rosario y Capital (Santa Fe)" dos,
etc.

Exclusiones deliberadas (no son nodos productivos o estan fuera de alcance):
  * Centros de distribucion de Grupo Calidra (Rosario, Cordoba, Campana,
    Resistencia, Santiago de Chile) -- sin produccion.
  * Sucursales comerciales de IMSA (Rosario, Santa Fe, Cordoba) -- sin produccion.
  * Operacion de IMSA/Neorol en Montevideo, Uruguay -- fuera de Argentina.
  * "Molino harinero historico La Clara" -- el propio documento lo marca fuera
    de alcance.
  * "Ilva" -- marca comercial de Ceramica San Lorenzo, no una planta.
  * Fila resumen "Vulcano, Randon, Helvetica, Cometto, Sola y Brusa" de la
    seccion 6 -- remite al desglose 6.bis, que si esta cargado.
  * "Ex plantas Morteros y Chivilcoy" de SanCor -- esas plantas ya figuran
    como registros de Adecoagro.

Campos del dict
---------------
id                    Identificador estable: IND-<COD>-<NNN>, secuencia en
                      orden de aparicion en el documento.
empresa               Razon social / grupo controlante.
planta                Nombre de la planta o complejo.
categoria             Una de las 8 categorias canonicas (ver CATEGORIAS).
categoria_cod         Codigo de 3 letras de la categoria.
subsector             Sub-rubro fino (Cemento, Cal, Yeso, Hormigon, Acero
                      plano, Aluminio, Lacteos, Molineria, Remolques, ...).
tipo                  PLANTA | POLO_REGIONAL | CANTERA | PUERTO | CENTRAL_ENERGETICA
producto_principal    Producto declarado en el documento.
capacidad_declarada   Capacidad tal como la declara el documento; "Sin dato
                      publico oficial" cuando el documento dice "s/d" o "-".
origen_materia_prima  Idem, con el mismo relleno por defecto.
estado_operativo      ACTIVA | CERRADA | EN_QUIEBRA/SUBASTA
ubicacion_texto       Ubicacion textual verbatim del documento.
localidad             Localidad normalizada usada para validar el geocoding.
provincia             Provincia normalizada usada para validar el geocoding.
notas                 Observaciones del curador (opcional).
sin_ubicar            True cuando el documento no da un lugar localizable.
geocode               Lista ordenada de consultas candidatas a Nominatim. Gana
                      la primera que sea aceptada. Cada candidato es
                      {"q": consulta, "precision": "EXACTA"|"ESTIMADA",
                       "solo_feature": bool}. ``solo_feature`` marca las
                      consultas por nombre de empresa/planta: si Nominatim
                      devuelve el centroide de la ciudad en vez de un rasgo
                      real (landuse=industrial, man_made=works, etc.) el
                      candidato se descarta y se pasa al siguiente.
"""

