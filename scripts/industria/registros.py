# --------------------------------------------------------------------------
# Helpers de construccion (mantienen el registro legible sin perder campos)
# --------------------------------------------------------------------------

def _ef(q: str) -> dict:
    """Candidato EXACTA por nombre de empresa/planta (exige rasgo real)."""
    return {"q": q, "precision": "EXACTA", "solo_feature": True}


def _e(q: str) -> dict:
    """Candidato EXACTA por direccion, parque industrial, paraje o villa."""
    return {"q": q, "precision": "EXACTA", "solo_feature": False}


def _a(q: str) -> dict:
    """Candidato ESTIMADA: centroide de localidad."""
    return {"q": q, "precision": "ESTIMADA", "solo_feature": False}


def _r(
    id: str,
    empresa: str,
    planta: str,
    categoria_cod: str,
    subsector: str,
    producto_principal: str,
    capacidad_declarada: str,
    origen_materia_prima: str,
    ubicacion_texto: str,
    localidad: str,
    provincia: str,
    geocode: list,
    tipo: str = "PLANTA",
    estado_operativo: str = "ACTIVA",
    notas: str = "",
    sin_ubicar: bool = False,
) -> dict:
    return {
        "id": id,
        "empresa": empresa,
        "planta": planta,
        "categoria": CATEGORIAS[categoria_cod],
        "categoria_cod": categoria_cod,
        "subsector": subsector,
        "tipo": tipo,
        "producto_principal": producto_principal,
        "capacidad_declarada": capacidad_declarada or SIN_DATO,
        "origen_materia_prima": origen_materia_prima or SIN_DATO,
        "estado_operativo": estado_operativo,
        "ubicacion_texto": ubicacion_texto,
        "localidad": localidad,
        "provincia": provincia,
        "notas": notas,
        "sin_ubicar": sin_ubicar,
        "geocode": geocode,
    }


